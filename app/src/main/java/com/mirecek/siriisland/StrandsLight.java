package com.mirecek.siriisland;

/**
 * Shared AGSL for the Strands orb: uniforms and functions used by {@link StrandsGlassShader} and
 * {@link FluidLensShader}. The light, body, ink and rim are ported from React Bits Strands
 * (https://reactbits.dev/animations/strands), Copyright (c) 2026 David Haz, MIT + Commons Clause;
 * fixed props (count 3, amplitude, thickness, taper, spread, scale, intensity, saturation 1, hue
 * shift 0, no lean) are folded into constants. Coordinates: u in orb half-widths, y up.
 *
 * <p>Ported from React Bits Strands (https://reactbits.dev), Copyright (c) 2026 David Haz, MIT + Commons Clause.
 *
 * <p>Source order in a shader: {@link #UNIFORMS}, {@link WaveStyles#UNIFORMS}, its own uniforms,
 * {@link WaveStyles#FUNCTIONS}, {@link #FUNCTIONS}, its main.
 */
final class StrandsLight {
    private StrandsLight() {}

    static final String UNIFORMS = String.join("\n",
        "uniform shader content;",     // captured wallpaper (or a 1x1 placeholder)
        "uniform float2 uOffset;",     // add to the fragment coordinate to get island pixels
        "uniform float2 uSize;",       // island width and height, px
        "uniform float uLevel;",       // Strands activity 0..1
        "uniform float uHasBackdrop;", // 1: refract the wallpaper
        "uniform float uBody;",        // body opacity over the wallpaper
        "uniform float uLight;",       // 0 dark orb .. 1 light orb
        "uniform float uIntro;",       // Strands intro 0..1
        "uniform float3 uMotion;",     // StrandsMotion.motion
        "uniform float3 uColors[7];",  // Themes.strandsColors
        "uniform float uSGlow;",       // Strands glow, 1 = React Bits default
        "uniform float uRim;",
        "uniform float uStrands;",     // 1 Strands light, 0 a WaveStyles style
        "uniform float uDispersion;",
        "uniform float uThink;",       // thinking layer 0..1 (eased in and out)
        "uniform float uThinkT;",      // thinking clock, s
        // React Bits Strands props (1 = its default unless noted).
        "uniform float uCount;",       // strands in the bulge, 1..3
        "uniform float uAmplitude;",
        "uniform float uSpread;",
        "uniform float uThickness;",
        "uniform float uTaper;",
        "uniform float uIntensity;",
        "uniform float uSaturation;",
        "uniform float uHueShift;",    // 0..1 turn
        "uniform float2 uLean;",       // Strands' lean (its pointer tilt), here the jelly pull
        "uniform float uStretch;",     // jelly stretch 0..1
        // Jelly transform of the live glass about the island centre: scale x, scale y, shift x, shift y
        // (px). The live glass is drawn unstretched so the wallpaper stays put; the shader stretches it.
        "uniform float4 uJelly;");

    static final String FUNCTIONS = String.join("\n",
        "float2 jellyIn(float2 ip) {",
        "    float2 hs = uSize * 0.5;",
        "    return hs + (ip - hs - uJelly.zw) / uJelly.xy;",
        "}",
        "",
        "float2 jellyOut(float2 p) {",
        "    float2 hs = uSize * 0.5;",
        "    return hs + (p - hs) * uJelly.xy + uJelly.zw;",
        "}",
        "",
        "const float PI = 3.14159265;",
        "",
        "float sstep(float a, float b, float x) {",
        "    float t = clamp((x - a) / (b - a), 0.0, 1.0);",
        "    return t * t * (3.0 - 2.0 * t);",
        "}",
        "",
        "float tanhf(float x) {",
        "    float e = exp(2.0 * clamp(x, -10.0, 10.0));",
        "    return (e - 1.0) / (e + 1.0);",
        "}",
        "",
        "float3 hueRotate(float3 c, float a) {",
        "    float3 yiq = float3(dot(c, float3(0.299, 0.587, 0.114)), dot(c, float3(0.596, -0.274, -0.322)),",
        "        dot(c, float3(0.211, -0.523, 0.312)));",
        "    float ca = cos(a);",
        "    float sa = sin(a);",
        "    yiq.yz = float2(ca * yiq.y - sa * yiq.z, sa * yiq.y + ca * yiq.z);",
        "    return max(float3(yiq.x + 0.956 * yiq.y + 0.621 * yiq.z, yiq.x - 0.272 * yiq.y - 0.647 * yiq.z,",
        "        yiq.x - 1.106 * yiq.y + 1.703 * yiq.z), 0.0);",
        "}",
        "",
        "float3 grade(float3 c) {",
        "    float g = dot(c, float3(0.2126, 0.7152, 0.0722));",
        "    c = clamp(mix(float3(g), c, 1.5 * uSaturation), 0.0, 1.0);",
        "    return uHueShift > 0.001 ? hueRotate(c, uHueShift * 6.2831853) : c;",
        "}",
        "",
        "float3 lightInk(float3 L, float halo, float3 body) {",
        "    float3 Lg = grade(L);",
        "    float lum = dot(Lg, float3(0.2126, 0.7152, 0.0722));",
        "    float cov = 1.0 - exp(-lum * 2.6);",
        "    float3 hn = Lg / max(max(Lg.r, max(Lg.g, Lg.b)), 1e-4);",
        "    float white = pow(clamp(min(hn.r, min(hn.g, hn.b)), 0.0, 1.0), 1.4);",
        "    float3 ink = pow(hn, float3(2.2)) * 0.88;",
        "    float coreAmt = white * smoothstep(0.05, 2.2, lum) * 0.92;",
        "    float3 cream = mix(mix(uColors[3], float3(1.0), 0.3), float3(1.0, 0.985, 0.95), smoothstep(1.2, 3.5, lum));",
        "    float3 c = mix(body, float3(0.66, 0.69, 0.76), halo * 0.32);",
        "    c = mix(c, ink, cov * (1.0 - white));",
        "    return mix(c, cream, clamp(coreAmt, 0.0, 1.0));",
        "}",
        "",
        "float erfa(float x) {",
        "    float a = abs(x);",
        "    float t = 1.0 / (1.0 + 0.3275911 * a);",
        "    float y = 1.0 - ((((1.061405429 * t - 1.453152027) * t + 1.421413741) * t - 0.284496736) * t + 0.254829592) * t * exp(-a * a);",
        "    return x < 0.0 ? -y : y;",
        "}",
        "",
        "float3 grad4(float3 c0, float3 c1, float3 c2, float3 c3, float p1, float p2, float f) {",
        "    float3 c = mix(c0, c1, sstep(0.0, p1, f));",
        "    c = mix(c, c2, sstep(p1, p2, f));",
        "    return mix(c, c3, sstep(p2, 1.0, f));",
        "}",
        "",
        "float2 sheetW(float tt, float H, float sig, float sigB, float ridges) {",
        "    float ew = 0.04 * uThickness;",
        "    float res0 = 0.0;",
        "    float res1 = 0.0;",
        "    for (int pass = 0; pass < 2; pass++) {",
        "        float sg = pass == 0 ? sig : sigB;",
        "        float fill = 0.5 * (erfa(tt / sg) - erfa((tt - H) / sg)) / H;",
        "        float se = sqrt(sg * sg + 0.25 * ew * ew * H * H);",
        "        float de = (tt - H + 0.5 * ew * H) / se;",
        "        float eg = exp(-de * de) / (se * 1.7724539);",
        "        float rgw = sqrt(sg * sg + 0.0025 * H * H);",
        "        float d1 = (tt - 0.45 * H) / rgw;",
        "        float d2 = (tt - 0.241 * H) / rgw;",
        "        float rid = 0.04 * (exp(-d1 * d1) * step(1.5, ridges) + 0.7 * exp(-d2 * d2) * step(2.5, ridges)) / (rgw * 1.7724539);",
        "        float v = 0.6 * fill * (1.0 - 0.55 * uLight) + (1.6 * ew * 0.886 * eg + rid) * (1.0 + 1.3 * uLight);",
        "        if (pass == 0) res0 = v; else res1 = v;",
        "    }",
        "    return float2(res0, res1);",
        "}",
        "",
        "float axis(float x) {",
        "    float a = uAmplitude;",
        "    return -0.2318 + uLean.y * 0.06 + (-0.2394 + uLean.x * 0.1) * x + 0.2815 * a * x * x + 0.3368 * a * x * x * x;",
        "}",
        "",
        "float softp(float z) {",
        "    return 0.03 * log(1.0 + exp(clamp(z / 0.03, -60.0, 60.0)));",
        "}",
        "",
        "float3 light(float2 u, float fp, float bend, float level, out float halo) {",
        "    float amp = level < 0.65 ? mix(0.25, 1.0, sstep(0.0, 0.65, level)) : mix(1.0, 1.12, (level - 0.65) / 0.35);",
        "    float grow = clamp((amp - 0.25) / 0.75, 0.0, 1.25);",
        "    float x = u.x;",
        "    float uy = u.y;",
        "    float ya = axis(x);",
        "    float taper = max(uTaper, 0.05);",
        "    float bq = (x - 0.0437 - uMotion.z - uLean.x * 0.08) / (0.6879 * taper);",
        "    float bump = exp(-bq * bq);",
        "    float hW = 0.02 + softp(-0.12 + 0.5324 * uAmplitude * grow * uMotion.y * bump - 0.02);",
        "    float k = uWavy;",
        "    float cphi = cos(0.5 * PI + k * (x + 0.0664) + uMotion.x);",
        "    float eq = (x - 0.0634) / 0.6873;",
        "    float envC = (0.0886 + 0.3 * exp(-eq * eq)) * uSpread * grow;",
        "    float hC = -envC * tanhf(cphi / 0.6);",
        "    float cq = cphi / 0.5;",
        "    float th = 0.051 * uThickness * exp(-cq * cq);",
        "    float sb = 0.005 + 0.05 * bend;",
        "    float sig = sqrt(sb * sb + fp * fp + th * th);",
        "    float g5 = max(uSGlow, 0.05);",
        "    float sigB = sqrt(0.0064 * g5 * g5 + fp * fp + th * th);",
        "    float mend = exp(-pow(abs((x + 0.0421) / (0.4235 * taper)), 2.2689));",
        "    float3 red = uColors[0];",
        "    float3 orange = uColors[1];",
        "    float3 amber = uColors[2];",
        "    float3 warmWhite = uColors[3];",
        "    float3 cyan = uColors[4];",
        "    float3 blue = uColors[5];",
        "    float3 deep = uColors[6];",
        "    float3 orangeEdge = orange * float3(1.0, 0.85, 0.77);",
        "    float3 coolCore = mix(warmWhite, float3(1.0, 1.0, 0.7), 0.6);",
        "    float3 mint = clamp(mix(cyan, warmWhite, 0.35) * float3(0.92, 1.05, 0.95), 0.0, 1.0);",
        "    float glow = max(uSGlow, 0.0);",
        "    float3 L = float3(0.0);",
        "    float3 Lb = float3(0.0);",
        "    {",
        "        float H = max(abs(hW), 1e-4);",
        "        float tt = uy - ya;",
        "        float2 w = sheetW(tt, H, sig, sigB, uCount);",
        "        float f = clamp(tt / H, 0.0, 1.0);",
        "        float3 c = grad4(warmWhite, amber, orange, orangeEdge, 0.2351, 0.5643, f);",
        "        c = mix(c, red, sstep(0.75, 1.0, f) * sstep(0.196, 0.3376, hW));",
        "        float3 mean = (grad4(warmWhite, amber, orange, orangeEdge, 0.2351, 0.5643, 0.1)",
        "            + grad4(warmWhite, amber, orange, orangeEdge, 0.2351, 0.5643, 0.35)",
        "            + grad4(warmWhite, amber, orange, orangeEdge, 0.2351, 0.5643, 0.6)",
        "            + grad4(warmWhite, amber, orange, orangeEdge, 0.2351, 0.5643, 0.9)) * 0.25;",
        "        L += mix(c, mean, sstep(0.3, 1.2, sig / H)) * (w.x * 0.2101 * mend);",
        "        Lb += mix(c, mean, sstep(0.3, 1.2, sigB / H)) * (w.y * 0.2101 * mend);",
        "    }",
        "    {",
        "        float H = max(abs(hC), 1e-4);",
        "        float tt = (uy - ya) * (hC >= 0.0 ? 1.0 : -1.0);",
        "        float2 w = sheetW(tt, H, sig, sigB, 1.0);",
        "        float f = clamp(tt / H, 0.0, 1.0);",
        "        float3 c = grad4(coolCore, cyan, blue, deep, 0.15, 0.7931, f);",
        "        float3 mean = (grad4(coolCore, cyan, blue, deep, 0.15, 0.7931, 0.1)",
        "            + grad4(coolCore, cyan, blue, deep, 0.15, 0.7931, 0.35)",
        "            + grad4(coolCore, cyan, blue, deep, 0.15, 0.7931, 0.6)",
        "            + grad4(coolCore, cyan, blue, deep, 0.15, 0.7931, 0.9)) * 0.25;",
        "        L += mix(c, mean, sstep(0.3, 1.2, sig / H)) * (w.x * 0.28 * mend);",
        "        Lb += mix(c, mean, sstep(0.3, 1.2, sigB / H)) * (w.y * 0.28 * mend);",
        "    }",
        "    float3 G = float3(0.0);",
        "    float wh = sqrt(0.0256 + envC * envC * cphi * cphi);",
        "    float dg = (uy - ya) / wh;",
        "    G += float3(1.0, 0.97, 0.92) * (exp(-dg * dg) * 0.0315 / wh * mend * glow);",
        "    float nx = -0.0664 - uMotion.x / k + 0.2168;",
        "    float bxx = (x - nx) / 0.1849;",
        "    float byy = (uy - axis(nx) - 0.0333) / (0.0544 * mix(0.7, 1.0, min(amp, 1.0)));",
        "    G += mint * (exp(-bxx * bxx - byy * byy) * 1.4 * glow * sstep(0.0, 0.6, amp));",
        "    float hb = (uy - ya - 0.3 * hW) / (0.07 + 0.45 * hW + 0.3 * envC);",
        "    float appear = smoothstep(0.0, 0.3, uIntro);",
        "    halo = exp(-hb * hb) * mend * appear;",
        "    float3 total = L + 0.16 * glow * Lb + 1.16 * G;",
        "    return total * 2.4 * uIntensity * appear * sstep(uIntro * 1.6, uIntro * 1.6 - 0.5, abs(x));",
        "}",
        "",
        // Strands light, or one of the classic styles in the same coordinates.
        "float3 sceneLight(float2 u, float fp, float bend, float level, out float halo) {",
        "    if (uStrands > 0.5) return light(u, fp, bend, level, halo) * (1.0 - 0.45 * uThink);",
        "    halo = 0.0;",
        "    float2 p = float2(u.x - uLean.x * 0.08, -u.y + uLean.y * 0.06 - (uCenter - 0.5) * 2.0 * uSize.y / uSize.x);",
        "    return waveStyle(p) * 0.9 * uIntensity * smoothstep(0.0, 0.3, uIntro) * (1.0 - 0.45 * uThink);",
        "}",
        "",
        // Thinking: two comets (warm, cool) orbit just inside the rim with fading tails in the theme
        // colours, and a soft core breathes in the middle. v: orb coordinates, rho: 0 centre .. 1 rim.
        "float3 thinkGlow(float2 v, float rho) {",
        "    if (uThink < 0.002) return float3(0.0);",
        "    float r = min(rho, 1.0);",
        "    float a = atan(v.y, v.x);",
        "    float shimmer = 0.85 + 0.15 * sin(3.0 * a - 5.0 * uThinkT);",
        "    float3 c = float3(0.0);",
        "    for (int i = 0; i < 2; i++) {",
        "        float head = 0.5 * PI + 3.4 * uThinkT + float(i) * PI;",
        "        float behind = mod(head - a, 2.0 * PI);",
        "        float dh = min(behind, 2.0 * PI - behind) / 0.22;",
        "        float w = exp(-behind * 1.15) * sstep(0.0, 0.35, behind) * sstep(PI, 2.6, behind) + 0.75 * exp(-dh * dh);",
        "        float f = behind > PI ? 0.0 : clamp(behind / 2.6, 0.0, 1.0);",
        "        float bw = 0.12 * (1.0 - 0.45 * f);",
        "        float bq = (r - 0.8) / bw;",
        "        float3 h = i == 0 ? mix(uColors[3], float3(1.0), 0.4) : mix(uColors[4], float3(1.0), 0.45);",
        "        float3 m = i == 0 ? uColors[1] : uColors[4];",
        "        float3 e = i == 0 ? uColors[0] : uColors[5];",
        "        float3 col = mix(mix(h, m, sstep(0.0, 0.35, f)), e, sstep(0.35, 1.0, f));",
        "        c += col * (w * exp(-bq * bq) * 1.6);",
        "    }",
        "    float cq = r / 0.42;",
        "    float breathe = 0.55 + 0.45 * cos(2.0 * PI * 0.8 * uThinkT);",
        "    c = c * shimmer + mix(uColors[3], float3(1.0), 0.35) * (exp(-cq * cq) * 0.35 * breathe);",
        "    return c * uThink * smoothstep(0.0, 0.3, uIntro);",
        "}",
        "",
        // Body (wallpaper behind it at 1 - uBody), strands light, Strands' rim ring, key light and haze,
        // iOS 27 rim colour; dark and light orbs crossfade by uLight.
        "float3 orbShade(float3 bg, float3 col, float3 L, float halo, float2 v, float rho, float bend, float level) {",
        "    float r = min(rho, 0.9995);",
        "    float2 d = v / max(length(v), 1e-6);",
        "    float rq = (r - 0.985) / 0.011;",
        "    float ring = exp(-rq * rq);",
        "    float key = 0.4 * pow(max(0.0, d.x * 0.94 - d.y * 0.34), 6.0) + 0.2 * pow(max(0.0, -d.x * 0.5 + d.y * 0.87), 6.0);",
        "    float hzk = 0.25 + 0.7 * pow(max(0.0, -d.x * 0.6 + d.y * 0.8), 2.0) + pow(max(0.0, d.x * 0.8 - d.y * 0.6), 2.0);",
        "    float hq = (1.0 - r) / 0.09;",
        "    float haze = exp(-hq * hq) * hzk * 0.13 * uRim;",
        "    float3 rimCol = mix(float3(0.651), float3(0.859), uLight);",
        "    float cover = mix(1.0, uBody, uHasBackdrop);",
        "    float3 darkBase = mix(bg, float3(0.04), cover);",
        // The rim catches light where the jelly is pulled (uLean points along the pull).
        "    float2 ld = uLean / max(length(uLean), 1e-4);",
        "    float pull = uStretch * pow(max(0.0, dot(d, ld)), 4.0);",
        "    float3 dark = darkBase + col * (1.0 + 0.1 * bend * uRim) + ring * key * uRim * (1.0 + 0.4 * level)",
        "        + haze * float3(1.0, 1.02, 1.04) * (1.0 + 2.0 * pull) + rimCol * ring * (0.25 + 1.2 * pull);",
        "    float lz = dot(d * r, float2(-0.55, 0.83));",
        "    float3 body = mix(float3(0.885, 0.893, 0.915), float3(0.972, 0.975, 0.983), 0.5 + 0.5 * lz);",
        "    float fres = smoothstep(0.8, 1.0, r);",
        "    body = mix(body, float3(0.82, 0.83, 0.86), fres * fres * 0.5);",
        "    float3 lit = lightInk(L, halo, mix(bg, body, cover));",
        "    float sq = (r - 0.955) / 0.03;",
        "    float spec = exp(-sq * sq) * pow(max(0.0, dot(d, float2(-0.55, 0.83))), 3.0);",
        "    lit = mix(lit, float3(1.0), clamp(spec * 0.85 * uRim + haze * 0.6, 0.0, 1.0));",
        "    lit = mix(lit, rimCol, ring * 0.35);",
        "    lit = mix(lit, float3(1.0), clamp(ring * pull * 0.9, 0.0, 1.0));",
        // Strands' light orb: a hairline darker edge just inside the outline.
        "    float eq2 = (1.0 - r) / (0.01 + 2.4 / uSize.x);",
        "    lit *= 1.0 - 0.12 * exp(-eq2 * eq2);",
        "    return clamp(mix(dark, lit, uLight), 0.0, 1.0);",
        "}");
}
