package com.mirecek.siriisland;

/**
 * 3D glass (spec §1.2): a ray-marched glass capsule (circle for the orb) with refraction, total
 * internal reflection, dispersion and a Fresnel studio reflection, ported from React Bits Fluid Glass
 * (https://reactbits.dev/components/fluid-glass, Copyright (c) 2026 David Haz, MIT + Commons Clause).
 * The Strands light is seen through the glass at the ray's exit point. Rays are orthographic (straight
 * down -z); the screen plane is z = 0, coordinates are island pixels centred on the island, y down.
 *
 * <p>Ported from React Bits Fluid Glass (https://reactbits.dev), Copyright (c) 2026 David Haz, MIT + Commons Clause.
 */
final class FluidLensShader {
    private FluidLensShader() {}

    static final String SOURCE = String.join("\n",
        StrandsLight.UNIFORMS,
        WaveStyles.UNIFORMS,
        "uniform float uIor;",
        "uniform float uThick;",  // edge radius, px (the slab is 4 x uThick thick)
        "uniform float uZ;",      // height of the slab centre above the screen, px
        WaveStyles.FUNCTIONS,
        StrandsLight.FUNCTIONS,
        "",
        "float sdf(float3 p) {",
        "    float2 hs = uSize * 0.5;",
        "    float r = hs.y;",
        "    float outline = length(float2(max(abs(p.x) - (hs.x - r), 0.0), p.y)) - r;",
        "    float e = uThick;",
        "    float2 q = float2(outline + e, abs(p.z - uZ) - e);",
        "    return length(max(q, float2(0.0))) + min(max(q.x, q.y), 0.0) - e;",
        "}",
        "",
        "float3 nrm(float3 p) {",
        "    float2 k = float2(1.0, -1.0);",
        "    float e = 0.5;",
        "    return normalize(k.xyy * sdf(p + k.xyy * e) + k.yyx * sdf(p + k.yyx * e)",
        "        + k.yxy * sdf(p + k.yxy * e) + k.xxx * sdf(p + k.xxx * e));",
        "}",
        "",
        "float2 landing(float3 o, float3 d) {",
        "    return o.xy + d.xy * (-o.z / min(d.z, -0.05));",
        "}",
        "",
        "half4 main(float2 fc) {",
        "    float2 ip = jellyIn(fc + uOffset);",
        "    float2 hs = uSize * 0.5;",
        "    float3 rd = float3(0.0, 0.0, -1.0);",
        "    float3 p0 = float3(ip - hs, uZ + 3.0 * uThick);",
        "    float3 p = p0;",
        "    float t = 0.0;",
        "    for (int i = 0; i < 40; i++) {",
        "        p = p0 + rd * t;",
        "        float d = sdf(p);",
        "        if (d < 0.3) break;",
        "        t += d;",
        "        if (t > 6.0 * uThick) break;",
        "    }",
        "    float3 n = nrm(p);",
        "    float3 inside = refract(rd, n, 1.0 / uIor);",
        "    float3 q = p + inside;",
        "    float3 exitN = n;",
        "    float3 exitDir = inside;",
        "    float escaped = 0.0;",
        "    for (int b = 0; b < 2; b++) {",
        "        for (int i = 0; i < 32; i++) {",
        "            float d = sdf(q);",
        "            if (d > -0.3) break;",
        "            q += inside * max(-d * 0.9, 0.3);",
        "        }",
        "        exitN = nrm(q);",
        "        float3 o1 = refract(inside, -exitN, uIor);",
        "        if (dot(o1, o1) > 0.0) { exitDir = o1; escaped = 1.0; break; }",
        "        inside = reflect(inside, -exitN);",
        "        q += inside;",
        "    }",
        "    if (escaped < 0.5) exitDir = inside;",
        "    if (exitDir.z > -0.2) exitDir = normalize(float3(exitDir.xy, -0.2 - abs(exitDir.z)));",
        "    float2 land = landing(q, exitDir);",
        "    float3 bg = float3(0.0);",
        "    if (uHasBackdrop > 0.5) {",
        "        float3 dirR = refract(inside, -exitN, uIor - 0.06 * uDispersion);",
        "        float3 dirB = refract(inside, -exitN, uIor + 0.06 * uDispersion);",
        "        float2 lr = (escaped > 0.5 && dot(dirR, dirR) > 0.0 && dirR.z < -0.2) ? landing(q, dirR) : land;",
        "        float2 lb = (escaped > 0.5 && dot(dirB, dirB) > 0.0 && dirB.z < -0.2) ? landing(q, dirB) : land;",
        "        bg.r = content.eval(jellyOut(hs + lr) - uOffset).r;",
        "        bg.g = content.eval(jellyOut(hs + land) - uOffset).g;",
        "        bg.b = content.eval(jellyOut(hs + lb) - uOffset).b;",
        "    }",
        "    float level = clamp(uLevel, 0.0, 1.0);",
        "    float2 v = float2(ip.x - hs.x, hs.y - ip.y) / hs.x;",
        "    float2 u = float2(land.x, -land.y) / hs.x;",
        "    float rr = hs.y;",
        "    float outline = length(float2(max(abs(ip.x - hs.x) - (hs.x - rr), 0.0), ip.y - hs.y)) - rr;",
        "    float rho = clamp(1.0 + outline / rr, 0.0, 1.0);",
        "    float bend = clamp(1.0 - abs(n.z), 0.0, 1.0);",
        "    float halo;",
        "    float3 L = sceneLight(u, 1.0 / hs.x, bend, level, halo);",
        "    L += thinkGlow(v, rho);",
        "    float3 col = grade(1.0 - exp(-L));",
        "    float3 c = orbShade(bg, col, L, halo, v, rho, bend, level);",
        "    float cosi = clamp(-dot(rd, n), 0.0, 1.0);",
        "    float f0 = pow((uIor - 1.0) / (uIor + 1.0), 2.0);",
        "    float fres = f0 + (1.0 - f0) * pow(1.0 - cosi, 5.0);",
        "    float3 m = reflect(rd, n);",
        "    float2 a = float2(atan(m.x, m.z), -m.y);",
        "    float key = smoothstep(0.42, 0.22, abs(a.x + 0.62)) * smoothstep(0.3, 0.12, abs(a.y - 0.5));",
        "    float strip = smoothstep(0.12, 0.05, abs(a.x - 0.95)) * smoothstep(0.8, 0.35, abs(a.y - 0.05));",
        "    c += float3(clamp(18.0 * key + 8.0 * strip, 0.0, 1.0)) * fres;",
        "    return half4(half3(clamp(c, 0.0, 1.0)), 1.0);",
        "}");
}
